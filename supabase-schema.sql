create or replace function public.create_meetup_round()
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  first_suggester uuid;
  second_suggester uuid;
  new_round_id bigint;
begin
  select id into first_suggester from public.profiles order by random() limit 1;
  select id into second_suggester from public.profiles where id <> first_suggester order by random() limit 1;
  if first_suggester is null or second_suggester is null then
    return null;
  end if;
  insert into public.meetup_rounds (suggester_one_id, suggester_two_id)
  values (first_suggester, second_suggester)
  returning id into new_round_id;
  return new_round_id;
end;
$$;

create or replace function public.submit_meetup_proposal(
  p_round_id bigint,
  p_activity text,
  p_place text,
  p_note text default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  proposal_id bigint;
begin
  if not exists (
    select 1 from public.meetup_rounds
    where id = p_round_id
      and (suggester_one_id = auth.uid() or suggester_two_id = auth.uid())
      and status = 'suggesting'
  ) then
    raise exception 'You are not a selected suggester for this round';
  end if;
  insert into public.meetup_proposals (round_id, author_id, activity, place, note)
  values (p_round_id, auth.uid(), trim(p_activity), trim(p_place), nullif(trim(p_note), ''))
  on conflict (round_id, author_id) do update set activity = excluded.activity, place = excluded.place, note = excluded.note
  returning id into proposal_id;
  if (select count(*) from public.meetup_proposals where round_id = p_round_id) = 2 then
    update public.meetup_rounds set status = 'voting' where id = p_round_id;
  end if;
  return proposal_id;
end;
$$;

create or replace function public.submit_meetup_vote(p_round_id bigint, p_proposal_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (select 1 from public.meetup_proposals where id = p_proposal_id and round_id = p_round_id) then
    raise exception 'That meet up idea is not part of this round';
  end if;
  insert into public.meetup_votes (round_id, proposal_id, voter_id)
  values (p_round_id, p_proposal_id, auth.uid())
  on conflict (round_id, voter_id) do nothing;
  if (select count(*) from public.meetup_votes where round_id = p_round_id) >= (select count(*) from public.profiles) then
    update public.meetup_rounds set status = 'complete' where id = p_round_id;
  end if;
end;
$$;

