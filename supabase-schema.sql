create table if not exists public.meetup_rounds (
  id bigint generated by default as identity primary key,
  suggester_one_id uuid not null references public.profiles (id) on delete cascade,
  suggester_two_id uuid not null references public.profiles (id) on delete cascade,
  status text not null default 'suggesting' check (status in ('suggesting', 'voting', 'complete')),
  created_at timestamptz not null default now(),
