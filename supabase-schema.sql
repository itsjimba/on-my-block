create or replace function public.allow_photo_login_attempt(p_profile_id uuid)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  attempt_count integer;
begin
  insert into public.photo_login_attempts as current_window (profile_id, window_started_at, attempts)
  values (p_profile_id, now(), 1)
  on conflict (profile_id) do update
  set window_started_at = case
        when current_window.window_started_at <= now() - interval '15 minutes'
          then excluded.window_started_at
        else current_window.window_started_at
      end,
      attempts = case
        when current_window.window_started_at <= now() - interval '15 minutes'
          then 1
        else current_window.attempts + 1
      end
  returning attempts into attempt_count;

  return attempt_count <= 5;
end;
$$;

revoke all on function public.allow_photo_login_attempt(uuid) from public, anon, authenticated;
grant execute on function public.allow_photo_login_attempt(uuid) to service_role;

